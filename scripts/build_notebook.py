        "    pred_bin = (probs >= threshold).float()",
        "    target_bin = (targets >= 0.5).float()",
        "    intersection = (pred_bin * target_bin).sum().item()",
        "    union = pred_bin.sum().item() + target_bin.sum().item() - intersection",
        "    return (intersection + eps) / (union + eps)",
